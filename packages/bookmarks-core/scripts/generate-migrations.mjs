// Renders the checked-in SQL migrations from `bookmarksTables` (the built package's @superfunctions/db table map).
// `npm run migrations` rewrites them; test/migrations.test.mjs fails when they differ from this output.
// @superfunctions/cli 0.2.0 generates migrations only by introspecting a live database and does not export its
// generators, so this narrow renderer covers the column types the Bookmarks tables use and rejects any other.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const DIALECTS = ['sqlite', 'postgres'];
export const INITIAL_MIGRATION = '0001_initial.sql';
/**
 * The migrations after the initial one, in order, each the optional columns it adds to a table. The initial migration
 * is rendered without them, so a database made by an earlier version reaches the same tables.
 */
export const LATER_MIGRATIONS = [{ name: '0002_bookmarks_added_at.sql', table: 'bookmarks', columns: ['addedAt'] }];
export const MIGRATIONS = [INITIAL_MIGRATION, ...LATER_MIGRATIONS.map((migration) => migration.name)];

const PRIMARY_KEY = ['__ns', 'id'];

function columnType(field, dialect, label) {
  const postgres = dialect === 'postgres';
  switch (field.type) {
    case 'string':
      return 'TEXT';
    case 'number':
      // Every Bookmarks number is an integer (apiId and the bookmark_api_ids value) that only grows, so 64-bit.
      return postgres ? 'BIGINT' : 'INTEGER';
    case 'boolean':
      return postgres ? 'BOOLEAN' : 'INTEGER';
    case 'json':
      return postgres ? 'JSONB' : 'TEXT';
    case 'date':
      if (field.dateValueType !== 'epoch-ms' || field.dateStorageType !== 'epoch-ms-bigint') break;
      return postgres ? 'BIGINT' : 'INTEGER';
  }
  throw new Error(`${label}: no SQL type for ${JSON.stringify(field)}`);
}

const quote = (name) => {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) throw new Error(`Unsafe SQL identifier ${name}`);
  return `"${name}"`;
};

export function renderMigration(tables, dialect) {
  if (!DIALECTS.includes(dialect)) throw new Error(`Unknown dialect ${dialect}`);
  const lines = [
    `-- Bookmarks schema version 1 for ${dialect === 'postgres' ? 'Postgres' : 'SQLite and Cloudflare D1'}.`,
    '-- Generated by scripts/generate-migrations.mjs from bookmarksTables; do not edit by hand.',
    ''
  ];
  for (const [model, table] of Object.entries(tables)) {
    if (table.modelName !== model) throw new Error(`${model}: modelName is ${table.modelName}`);
    for (const column of PRIMARY_KEY) {
      if (table.fields[column]?.required !== true) throw new Error(`${model}: primary key column ${column} must be required`);
    }
    const definitions = Object.entries(table.fields).map(([name, field]) => {
      if (field.fieldName !== undefined && field.fieldName !== name) throw new Error(`${model}.${name}: renamed columns are not supported`);
      if (field.unique || field.defaultValue !== undefined) {
        throw new Error(`${model}.${name}: declare uniqueness as an index; defaults are not supported`);
      }
      return `  ${quote(name)} ${columnType(field, dialect, `${model}.${name}`)}${field.required ? ' NOT NULL' : ''}`;
    });
    definitions.push(`  PRIMARY KEY (${PRIMARY_KEY.map(quote).join(', ')})`);
    // A reference is to another table's id in the same namespace, so the key includes `__ns` on both sides.
    for (const [name, field] of Object.entries(table.fields)) {
      const ref = field.references;
      if (!ref) continue;
      if (!tables[ref.model] || ref.field !== 'id' || ref.onDelete !== 'cascade' || ref.onUpdate !== undefined) {
        throw new Error(`${model}.${name}: only references to another table's id with onDelete cascade are supported`);
      }
      definitions.push(`  FOREIGN KEY ("__ns", ${quote(name)}) REFERENCES ${quote(ref.model)} (${PRIMARY_KEY.map(quote).join(', ')}) ON DELETE CASCADE`);
    }
    for (const constraint of table.constraints ?? []) {
      if (constraint.type !== 'check' || typeof constraint.check !== 'string')
        throw new Error(`${model}: only check constraints are supported`);
      definitions.push(`  CONSTRAINT ${quote(constraint.name)} CHECK (${constraint.check})`);
    }
    lines.push(`CREATE TABLE ${quote(model)} (`, definitions.join(',\n'), ');');
    for (const index of table.indexes ?? []) {
      for (const field of index.fields) if (!table.fields[field]) throw new Error(`${model}.${index.name}: unknown column ${field}`);
      const columns = index.fields.map(quote).join(', ');
      lines.push(`CREATE ${index.unique ? 'UNIQUE ' : ''}INDEX ${quote(index.name)} ON ${quote(model)} (${columns});`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

/** Each migration's SQL by name, in order: the tables without the later columns, then each `ADD COLUMN`. */
export function renderMigrations(tables, dialect) {
  const initial = structuredClone(tables);
  for (const { table, columns } of LATER_MIGRATIONS) for (const column of columns) delete initial[table].fields[column];
  const sql = new Map([[INITIAL_MIGRATION, renderMigration(initial, dialect)]]);
  for (const { name, table, columns } of LATER_MIGRATIONS) {
    const lines = [
      `-- Bookmarks ${name} for ${dialect === 'postgres' ? 'Postgres' : 'SQLite and Cloudflare D1'}.`,
      '-- Generated by scripts/generate-migrations.mjs from bookmarksTables; do not edit by hand.',
      ''
    ];
    for (const column of columns) {
      const field = tables[table].fields[column];
      if (!field || field.required) throw new Error(`${table}.${column}: a later migration adds only optional columns`);
      lines.push(`ALTER TABLE ${quote(table)} ADD COLUMN ${quote(column)} ${columnType(field, dialect, `${table}.${column}`)};`);
    }
    sql.set(name, [...lines, ''].join('\n'));
  }
  return sql;
}

export const migrationPath = (dialect, name) => new URL(`../migrations/${dialect}/${name}`, import.meta.url);

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { bookmarksTables } = await import('../dist/index.js');
  for (const dialect of DIALECTS) {
    for (const [name, sql] of renderMigrations(bookmarksTables, dialect)) {
      const path = migrationPath(dialect, name);
      let current = null;
      try {
        current = readFileSync(path, 'utf8');
      } catch {}
      if (current !== sql) writeFileSync(path, sql);
      console.log(`${current === sql ? 'Unchanged' : 'Wrote'} migrations/${dialect}/${name}`);
    }
  }
}
