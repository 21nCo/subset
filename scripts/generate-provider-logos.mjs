// Regenerates packages/usage/src/provider-logos.ts from the CC0 Iconify "logos" set (gilbarbara/logos).
// Only the provider marks the view uses are copied, so the full icon set is never bundled.
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(new URL('../packages/usage/package.json', import.meta.url));
const { icons } = require('@iconify-json/logos');
const { getIconData, iconToSVG } = require('@iconify/utils');

// Near-black marks follow the text color so they stay visible in dark mode.
const marks = {
  'codex-chatgpt': ['openai-icon', true], 'claude-code': ['claude-icon', false], antigravity: ['antigravity', false], cursor: ['cursor-icon', true], 'cursor-local': ['cursor-icon', true],
  devin: ['devin', true], opencode: ['opencode-icon', true],
};
// Bodies are rendered with {@html}, so only static shapes are allowed: no scripts, event handlers,
// embedded documents or images, animation that can retarget attributes, links, or references
// other than same-document `#id` fragments.
// HTML media and document elements are listed too: inside inline SVG they break out into HTML content.
const ACTIVE_SVG = /<(?:script|foreignObject|image|img|iframe|frame|embed|object|video|audio|source|track|picture|canvas|link|meta|base|form|input|a|set|animate\w*|style)\b|\son[a-z]+\s*=|(?:xlink:)?href\s*=\s*(?!["']?\s*#)|javascript:|data:|url\(\s*(?!["']?\s*#)/i;
const assertStatic = (name, svg) => { if (ACTIVE_SVG.test(svg)) throw new Error(`${name} contains active or external content.`); };

const entries = Object.entries(marks).map(([provider, [name, mono]]) => {
  const data = getIconData(icons, name);
  if (!data) throw new Error(`Missing icon ${name}`);
  const svg = iconToSVG(data);
  let body = svg.body.replace(/fill="#(?:000|000000|26251e|211e1e|131010|0a0a0a|1a1a1a)"/gi, 'fill="currentColor"');
  // Element IDs (gradients, masks) are made unique per rendered instance by ProviderIcon.
  if (mono && !/fill=/.test(body)) body = `<g fill="currentColor">${body}</g>`;
  assertStatic(`logos:${name}`, body);
  return `  '${provider}': { icon: 'logos:${name}', viewBox: '${svg.attributes.viewBox}', body: ${JSON.stringify(body)} },`;
});


// Marks not in the Iconify set are vendored as reviewed, script-free SVG files in scripts/logos.
for (const [provider, file] of [['factory-droid', 'factory-droid.svg'], ['amp', 'amp.svg'], ['pi', 'pi.svg'], ['omp', 'omp.svg'], ['hermes', 'hermes.svg']]) {
  const svg = await readFile(new URL(`./logos/${file}`, import.meta.url), 'utf8');
  assertStatic(file, svg);
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  const body = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg)?.[1]?.trim();
  if (!viewBox || !body) throw new Error(`${file} is not a single SVG.`);
  // App icons with their own background fill the tile instead of sitting inside it.
  const fullBleed = provider === 'amp' || provider === 'omp' ? ', fullBleed: true' : '';
  entries.push(`  '${provider}': { icon: 'vendored:${file}', viewBox: '${viewBox}', body: ${JSON.stringify(body)}${fullBleed} },`);
}

const output = `// Generated by scripts/generate-provider-logos.mjs from @iconify-json/logos ${require('@iconify-json/logos/package.json').version}.
// Icons: gilbarbara/logos, CC0-1.0; Factory, Amp, Pi, omp, and Hermes marks from their sites (scripts/logos). Do not edit by hand.
export const providerLogos: Record<string, { icon: string; viewBox: string; body: string; fullBleed?: boolean }> = {
${entries.join('\n')}
};
`;
await writeFile(fileURLToPath(new URL('../packages/usage/src/provider-logos.ts', import.meta.url)), output);
